function standaloneMarkup(markup: string, id: string, description: string) {
  const source = markup.replace(
    /<style data-plotter-styles="true">[\s\S]*?<\/style>/,
    "",
  );
  return source.replace(/<svg\b[^>]*>/, (opening) => {
    const attributes = opening
      .replace(/\sclass="[^"]*"/, "")
      .replace(/\saria-hidden="true"/, "")
      .slice(0, -1);
    return `${attributes} xmlns="http://www.w3.org/2000/svg" width="560" height="440" role="img" aria-labelledby="${id}-title" aria-describedby="${id}-description"><title id="${id}-title">An assembly line</title><desc id="${id}-description">${description}</desc>`;
  });
}

